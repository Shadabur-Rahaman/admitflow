import {test,expect} from '../frontend/node_modules/@playwright/test'

test('searches the directory and operates filters by keyboard',async({page})=>{
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Hospital Overview'})).toBeVisible()
  const search=page.getByRole('searchbox',{name:'Search patients'}).or(page.getByRole('textbox',{name:'Search patients'}))
  await search.fill('Unmatched Browser Test')
  await search.press('Enter')
  await expect(page.getByText('No patients found')).toBeVisible()
  await page.getByRole('button',{name:'Clear filters'}).click()
  await expect(page.locator('tbody tr').first()).toBeVisible()
  const ward=page.getByRole('button',{name:'Wards',exact:true})
  await ward.focus()
  await ward.press('ArrowDown')
  await expect(page.getByRole('option',{name:'All wards',exact:true})).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(ward).toBeFocused()
  await expect(page).toHaveURL(/ward_id=/)
  await ward.press('Enter')
  await page.keyboard.press('Escape')
  await expect(ward).toBeFocused()
  await expect(page.getByRole('listbox',{name:'Wards'})).toHaveCount(0)
  const dates=page.getByRole('button',{name:'Dates',exact:true})
  await dates.click()
  await page.getByLabel('Admitted from').fill('2000-01-01')
  await expect(page).toHaveURL(/admission_from=2000-01-01/)
})

test('keeps the full patient identifier accessible and returns focus on close',async({page})=>{
  await page.goto('/patients')
  const row=page.locator('tbody .identity').first()
  await expect(row).toBeVisible()
  const code=await row.locator('small').getAttribute('title')
  await row.click()
  const dialog=page.getByRole('dialog')
  await expect(dialog.getByRole('textbox',{name:'Full patient ID'})).toHaveValue(code!)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(row).toBeFocused()
})

test('uses the report date range for both analytics and CSV',async({page})=>{
  await page.goto('/reports')
  await expect(page.getByRole('heading',{name:'Admission status'})).toBeVisible()
  await page.getByLabel('From date').fill('2000-01-01')
  await page.getByLabel('Through date').fill('2000-01-02')
  await expect(page.getByText('No admissions match this period.')).toBeVisible()
  await expect(page.getByRole('link',{name:'Export CSV'})).toHaveAttribute('href',/admission_from=2000-01-01&admission_to=2000-01-02$/)
  const csv=page.waitForEvent('download')
  await page.getByRole('link',{name:'Export CSV'}).click()
  expect((await csv).suggestedFilename()).toMatch(/\.csv$/)
  await page.getByLabel('Through date').fill('1999-12-31')
  await expect(page.getByRole('alert')).toHaveText('The through date must be on or after the from date.')
  await expect(page.getByRole('link',{name:'Export CSV'})).toHaveCount(0)
})

test('opens the directory from a ward and preserves its filter',async({page})=>{
  await page.goto('/wards')
  await expect(page.locator('.ward-preview .identity').first()).toBeVisible()
  await page.getByRole('link',{name:'View Patients',exact:true}).first().click()
  await expect(page).toHaveURL(/ward_id=general/)
  await expect(page.getByRole('button',{name:'Wards',exact:true})).toContainText('General Ward')
})

test('shows an API availability error and can recover on retry',async({page})=>{
  const endpoint='**/api/v1/dashboard/summary'
  const fail=async(route:import('../frontend/node_modules/@playwright/test').Route)=>route.abort('failed')
  await page.route(endpoint,fail)
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('Could not load admissions')
  await page.unroute(endpoint,fail)
  await page.getByRole('button',{name:'Try again'}).click()
  await expect(page.getByRole('heading',{name:'Hospital Overview'})).toBeVisible()
})
