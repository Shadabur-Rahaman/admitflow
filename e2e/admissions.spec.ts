import {test,expect} from '../frontend/node_modules/@playwright/test'

test('admit, filter, edit, discharge, and delete a fictional patient',async({page},info)=>{
  const stamp=Date.now().toString().replace(/[0-9]/g,digit=>'abcdefghij'[Number(digit)])
  const name=(info.project.name==='mobile'?'Mara Mobile':'Mara Desktop')+stamp
  await page.goto('/patients')
  const directory=page.getByRole('heading',{name:'Patient Directory'})
  await expect(directory).toBeVisible()
  const active=page.locator('.metric').filter({hasText:'Currently Admitted'}).locator('strong')
  const originalActive=Number(await active.innerText())
  await page.getByRole('button',{name:'New Admission'}).last().click()
  const dialog=page.getByRole('dialog')
  await dialog.getByLabel('Patient name').fill(name)
  await dialog.getByLabel('Age',{exact:true}).fill('32')
  await dialog.getByLabel('Gender').selectOption('Female')
  await dialog.getByLabel('Ward').selectOption('general')
  await dialog.getByLabel('Department').selectOption('medicine')
  await dialog.getByLabel('Doctor').selectOption('doctor-1')
  await dialog.getByRole('button',{name:'Admit Patient'}).click()
  await expect(page.getByText('Patient admitted successfully.')).toBeVisible()
  await expect(active).toHaveText(String(originalActive+1))
  await page.getByLabel('Search by patient name').fill(name.toLowerCase())
  await expect(page.getByText('1 matching records')).toBeVisible()
  await page.getByLabel('Wards',{exact:true}).selectOption('general')
  await page.getByLabel('Departments',{exact:true}).selectOption('medicine')
  await page.getByLabel('Doctors',{exact:true}).selectOption('doctor-1')
  await page.getByRole('button',{name:new RegExp(name)}).first().click()
  await expect(dialog.getByText('General Ward')).toBeVisible()
  await dialog.getByRole('button',{name:'Edit Patient'}).click()
  await dialog.getByLabel('Age',{exact:true}).fill('33')
  await dialog.getByRole('button',{name:'Save Changes'}).click()
  await expect(page.getByText('Patient information updated.')).toBeVisible()
  await page.reload()
  await expect(page.getByText('33 · Female')).toBeVisible()
  await page.getByLabel('Actions for '+name).click()
  await page.getByRole('button',{name:'Discharge Patient'}).click()
  await dialog.getByRole('button',{name:'Discharge Patient'}).click()
  await expect(page.locator('.status.discharged')).toHaveText('Discharged')
  await expect(active).toHaveText(String(originalActive))
  await page.getByLabel('Actions for '+name).click()
  await page.getByRole('button',{name:'Delete Patient'}).click()
  await dialog.getByRole('button',{name:'Cancel'}).click()
  await expect(page.getByText(name,{exact:true})).toBeVisible()
  await page.getByLabel('Actions for '+name).click()
  await page.getByRole('button',{name:'Delete Patient'}).click()
  await dialog.getByRole('button',{name:'Delete Patient'}).click()
  await expect(page.getByRole('heading',{name:'No patients found'})).toBeVisible()
})

