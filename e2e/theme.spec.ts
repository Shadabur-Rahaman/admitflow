import {test, expect} from '../frontend/node_modules/@playwright/test'

test('appearance follows the system and persists a manual choice', async ({page}) => {
  await page.emulateMedia({colorScheme: 'dark', reducedMotion: 'reduce'})
  await page.goto('/')
  const root = page.locator('html')
  const theme = page.getByRole('button', {name: 'Appearance'})
  const apply = async (mode:string) => {
    await theme.click()
    await page.getByRole('option',{name:mode,exact:true}).click()
  }
  await expect(root).toHaveCSS('color-scheme', 'dark')
  await apply('Light')
  await expect(root).toHaveCSS('color-scheme', 'light')
  await page.reload()
  await expect(root).toHaveAttribute('data-theme','light')
  await apply('Dark')
  await expect(root).toHaveCSS('color-scheme', 'dark')
  await expect(page.getByRole('heading', {name:'Hospital Overview'})).toBeVisible()
  await expect(page.locator('.recharts-bar').first()).toBeVisible()
  await page.getByRole('link',{name:'Patients',exact:true}).click()
  await expect(page.locator('tbody tr').first()).toBeVisible()
  await page.getByRole('button',{name:'New Admission',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCSS('color', 'rgb(243, 244, 242)')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await apply('System')
  await expect(root).toHaveCSS('color-scheme', 'dark')
  await page.emulateMedia({colorScheme:'light'})
  await expect(root).toHaveCSS('color-scheme', 'light')
})
