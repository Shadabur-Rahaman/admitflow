import {test, expect} from '../frontend/node_modules/@playwright/test'

test('appearance follows the system and persists a manual choice', async ({page}, info) => {
  test.skip(info.project.name === 'mobile')
  await page.emulateMedia({colorScheme: 'dark', reducedMotion: 'reduce'})
  await page.goto('/')
  const root = page.locator('html')
  const theme = page.getByRole('combobox', {name: 'Appearance'})
  await expect(root).toHaveCSS('color-scheme', 'dark')
  await theme.selectOption('light')
  await expect(root).toHaveCSS('color-scheme', 'light')
  await page.reload()
  await expect(theme).toHaveValue('light')
  await theme.selectOption('dark')
  await expect(root).toHaveCSS('color-scheme', 'dark')
  await expect(page.getByRole('heading', {name:'Hospital Overview'})).toBeVisible()
  await expect(page.locator('.recharts-area').first()).toBeVisible()
  await page.getByRole('link',{name:'Patients',exact:true}).click()
  await expect(page.locator('tbody tr').first()).toBeVisible()
  await page.getByRole('button',{name:'New Admission'}).last().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCSS('color', 'rgb(246, 237, 230)')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
